//! Tool declaration and configuration params.

use serde::{Serialize, Deserialize};

/// Tool details that the model may use to generate response.
///
/// A Tool is a piece of code that enables the system to interact with
/// external systems to perform an action, or set of actions, outside
/// of knowledge and scope of the model.
///
/// See: [API Reference](https://ai.google.dev/api/caching#Tool)
#[derive(Serialize, Debug, Clone, Default)]
#[serde(rename_all = "camelCase")]
pub struct Tool {

    /// A list of [FunctionDeclaration] available to the model that can
    /// be used for function calling.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub function_declarations: Vec<serde_json::Value>,

    /// Enables the model to execute code as part of generation.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub code_execution: Option<CodeExecution>,

    /// [GoogleSearch] tool type.
    ///
    /// Tool to support Google Search in Model. Powered by Google.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub google_search: Option<GoogleSearch>,

    /// Tool to support the model interacting directly with the
    /// computer.
    ///
    /// If enabled, it automatically populates computer-use specific
    /// Function Declarations.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub computer_use: Option<ComputerUse>,

    /// Tool to support URL context retrieval.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub url_context: Option<UrlContext>,

    /// FileSearch tool type.
    ///
    /// Tool to retrieve knowledge from Semantic Retrieval corpora.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub file_search: Option<FileSearch>,

    /// Tool that allows grounding the model's response with
    /// geospatial context related to the user's query.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub google_maps: Option<GoogleMaps>,
}

impl From<serde_json::Value> for Tool {
    fn from(schema: serde_json::Value) -> Self {
        let mut tool = Tool::default();
        tool.function_declarations.push(schema);
        tool
    }
}

impl Tool {

    /// Create a [Tool] that enables remote code execution.
    ///
    /// See also: [CodeExecution].
    pub fn code_execution() -> Self {
        Self { code_execution: Some(CodeExecution{}), ..Self::default() }
    }

    /// Create a [Tool] that enables Google Search grounding.
    ///
    /// See also: [GoogleSearch].
    pub fn google_search(time_range_filter: Option<Interval>) -> Self {
        Self {
            google_search: Some(GoogleSearch {time_range_filter}),
            ..Self::default()
        }
    }

    /// Creates a [Tool] that handles URL context retrieval.
    pub fn url_context() -> Self {
        Self { url_context: Some(UrlContext {}), ..Self::default() }
    }

    /// Creates a [Tool] that handles file search.
    pub fn file_search() -> Self {
        todo!();
    }

    /// Creates a [Tool] that grounds the model's responses with
    /// geospatial context.
    ///
    /// See also: [GoogleMaps].
    ///
    /// Optionally provide the relevant location context by specifying
    /// the `lat_lng` coordinates in [RetrievalConfig].
    pub fn google_maps(enable_widget: Option<bool>) -> Self {
        Self {
            google_maps: Some(GoogleMaps{ enable_widget }),
            ..Self::default()
        }
    }
}

