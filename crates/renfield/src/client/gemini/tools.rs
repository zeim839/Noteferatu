/// Configuration for specifying function calling behavior.
///
/// See: [API Reference](https://ai.google.dev/api/caching#FunctionCallingConfig)
#[derive(Serialize, Debug, Clone)]
#[serde(rename_all = "camelCase")]
pub struct FunctionCallingConfig {

    /// Specifies the mode in which function calling should
    /// execute. If unspecified, the default value will be set to
    /// AUTO.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub mode: Option<FunctionCallingMode>,

    /// A set of function names that, when provided, limits the
    /// functions the model will call.
    ///
    /// This should only be set when the Mode is ANY or
    /// VALIDATED. Function names should match
    /// [FunctionDeclaration.name]. When set, model will predict a
    /// function call from only allowed function names.
    #[serde(skip_serializing_if = "Vec::is_empty")]
    pub allowed_function_names: Vec<String>,
}

/// Defines the execution behavior for function calling by defining
/// the execution mode.
///
/// See: [API Reference](https://ai.google.dev/api/caching#Mode_1)
#[derive(Serialize, Debug, Clone)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum FunctionCallingMode {

    /// Default model behavior, model decides to predict either a
    /// function call or a natural language response.
    Auto,

    /// Model is constrained to always predicting a function call
    /// only.
    ///
    /// If `allowed_function_names` are set, the predicted function
    /// call will be limited to any one of `allowed_function_names`,
    /// else the predicted function call will be any one of the
    /// provided `function_declarations`.
    Any,

    /// Model will not predict any function call.
    ///
    /// Model behavior is same as when not passing any function
    /// declarations.
    None,

    /// Model decides to predict either a function call or a natural
    /// language response, but will validate function calls with
    /// constrained decoding.
    Validated,
}

/// Retrieval config.
///
/// See: [API Reference](https://ai.google.dev/api/caching#RetrievalConfig)
#[derive(Serialize, Debug, Clone, Default)]
#[serde(rename_all = "camelCase")]
pub struct RetrievalConfig {

    /// The location of the user.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub lat_lng: Option<LatLng>,

    /// The language code of the user.
    ///
    /// Language code for content.
    ///
    /// Use language tags defined by BCP47.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub language_code: Option<String>,
}

impl RetrievalConfig {

    /// Create a [RetrievalConfig] from a pair of coordinates.
    pub fn new(latitude: f64, longitude: f64) -> Self {
        Self {
            lat_lng: Some(LatLng::new(latitude, longitude)),
            language_code: None,
        }
    }
}

/// An object that represents a latitude/longitude pair.
///
/// This is expressed as a pair of doubles to represent degrees
/// latitude and degrees longitude. Unless specified otherwise, this
/// object must conform to the WGS84 standard. Values must be within
/// normalized ranges.
///
/// See: [API Reference](https://ai.google.dev/api/caching#LatLng)
#[derive(Serialize, Debug, Clone)]
#[serde(rename_all = "camelCase")]
pub struct LatLng {

    /// The latitude in degrees.
    ///
    /// It must be in the range [-90.0, +90.0].
    pub latitude: f64,

    /// The longitude in degrees.
    ///
    /// It must be in the range [-180.0, +180.0].
    pub longitude: f64,
}

impl LatLng {

    /// Create a [LatLng] from a pair of coordinates.
    pub fn new(latitude: f64, longitude: f64) -> Self {
        Self { latitude, longitude }
    }
}

/// A predicted [`FunctionCall`] returned from the model that contains
/// a string representing the FunctionDeclaration.name with the
/// arguments and their values.
#[derive(Serialize, Deserialize, Debug, Clone)]
#[serde(rename_all = "camelCase")]
pub struct FunctionCall {

    /// The unique id of the function call.
    ///
    /// If populated, the client to execute the [FunctionCall] and
    /// return the response with the matching id.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub id: Option<String>,

    /// The name of the function to call.
    pub name: String,

    /// The function parameters and values in JSON object format.
    pub args: Option<serde_json::Value>,
}

/// The result output from a [FunctionCall].
///
/// See: [API Reference](https://ai.google.dev/api/caching#FunctionResponse)
#[derive(Serialize, Deserialize, Debug, Clone)]
#[serde(rename_all = "camelCase")]
pub struct FunctionResponse {

    /// The id of the function call this response is for.
    ///
    /// Populated by the client to match the corresponding function
    /// call id.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub id: Option<String>,

    /// The name of the function to call.
    pub name: String,

    /// The function response in JSON object format.
    ///
    /// Callers can use any keys of their choice that fit the
    /// function's syntax to return the function output.
    pub response: serde_json::Value,
}
